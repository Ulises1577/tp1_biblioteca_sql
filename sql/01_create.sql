-- Creacion de la base de datos
CREATE DATABASE IF NOT EXISTS Biblioteca_uni;
USE Biblioteca_uni;

-- Creamos las tablas independientes primero
CREATE TABLE CIUDAD (
    ID_CIUDAD INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL
);

CREATE TABLE AUTORES (
    RUT_AUTOR INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO VARCHAR(50) NOT NULL
);

CREATE TABLE EDITORIALES (
    ID_EDITORIAL INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    PAIS VARCHAR(50) NOT NULL
);

CREATE TABLE TIPO (
    ID_TIPO INT PRIMARY KEY,
    TIPO_P VARCHAR(50) NOT NULL
);

CREATE TABLE BIBLIOTECA (
    ID_BIBLIOTECA INT PRIMARY KEY,
    BIBLIOTECA VARCHAR(50) NOT NULL
);

-- Ahora voy con la creacion de las tablas dependientes

CREATE TABLE CAMPUS (
    ID_CAMPUS INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    ID_CIUDAD INT NOT NULL,
    FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

CREATE TABLE CARRERAS (
    ID_CARRERA INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE ESTUDIANTES (
    RUT_EST INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO VARCHAR(50) NOT NULL,
    EDAD INT NOT NULL,
    FONO VARCHAR(20) NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    ID_CARRERA INT NOT NULL,
    FOREIGN KEY (ID_CARRERA) REFERENCES CARRERAS(ID_CARRERA)
);

CREATE TABLE FUNCIONARIOS (
    RUT_FUNC INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO VARCHAR(50) NOT NULL,
    EDAD INT NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    SALUD VARCHAR(50) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE LIBROS (
    COD_LIBRO INT PRIMARY KEY,
    TITULO VARCHAR(100) NOT NULL,
    AGNO INT NOT NULL,
    ID_BIBLIOTECA INT NOT NULL,
    ID_TIPO INT NOT NULL,
    RUT_AUTOR INT NOT NULL,
    ID_EDITORIAL INT NOT NULL,
    FOREIGN KEY (ID_BIBLIOTECA) REFERENCES BIBLIOTECA(ID_BIBLIOTECA),
    FOREIGN KEY (ID_TIPO) REFERENCES TIPO(ID_TIPO),
    FOREIGN KEY (RUT_AUTOR) REFERENCES AUTORES(RUT_AUTOR),
    FOREIGN KEY (ID_EDITORIAL) REFERENCES EDITORIALES(ID_EDITORIAL)
);

-- Y esta seria una tabla dependiente con clave compuesta
CREATE TABLE PRESTAMOS (
    RUT_EST INT NOT NULL,
    RUT_FUNC INT NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_P DATE NOT NULL,
    FECHA_E DATE NOT NULL,
    PRIMARY KEY (RUT_EST, RUT_FUNC, COD_LIBRO),
    FOREIGN KEY (RUT_EST) REFERENCES ESTUDIANTES(RUT_EST),
    FOREIGN KEY (RUT_FUNC) REFERENCES FUNCIONARIOS(RUT_FUNC),
    FOREIGN KEY (COD_LIBRO) REFERENCES LIBROS(COD_LIBRO)
);

