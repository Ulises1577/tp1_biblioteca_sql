USE Biblioteca_uni;

-- FILTROS Y ORDENAMIENTOS BASICOS 

-- 1 TITULO Y AÑO
SELECT TITULO, AGNO FROM LIBROS ORDER BY AGNO ASC;

--2 NOMBRE Y APEELLIDO Y EDAD DE ESTUDIANTES MAYORES DE 25 AÑOS
SELECT NOMBRE, APELLIDO, EDAD FROM ESTUDIANTES WHERE EDAD > 25;

--3 TITULO Y AÑO DE LOS LIBROS DE LA EDITORIAL CON 3
SELECT TITULO, AGNO FROM LIBROS WHERE ID_EDITORIAL = 3;

--4 LISTA TODOS AUTORES CON APELLIDO QUE EMPIECE POR M
SELECT * FROM AUTORES WHERE APELLIDO LIKE 'M%';

--5 NOMBRE Y APELLIDO DE FUNCIONARIO CON SALUD DISTINTA A BUENA
SELECT NOMBRE, APELLIDO FROM FUNCIONARIOS WHERE SALUD != 'Buena';

-- UNIONES CON JOIN

--6 TITULO DEL LIBRO JUNTO CON EL NOMBRE Y APELLIDO DE SU AUTOR
SELECT L.TITULO, A.NOMBRE, A.APELLIDO FROM LIBROS L 
JOIN AUTORES A ON L.RUT_AUTOR = A.RUT_AUTOR

--7 DETALLE COMPLETO DE PRESTAMOS (FECHA, ESTUDIANTE, LIBRO Y FUNCIONARIO)

SELECT
    P.FECHA_P,
    CONCAT(E.NOMBRE, ' ', E.APELLIDO) AS ESTUDIANTE,
    L.TITULO,
    CONCAT(F.NOMBRE, ' ', F.APELLIDO) AS FUNCIONARIO
FROM PRESTAMOS P
JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
JOIN LIBROS L ON P.COD_LIBRO = L.COD_LIBRO
JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC;

--8 Estudiante, carrera y ciudad donde estudia
SELECT
    E.NOMBRE,
    E.APELLIDO,
    CA.NOMBRE AS CARRERA,
    CI.NOMBRE AS CIUDAD
FROM ESTUDIANTES E 
JOIN CARRERAS CA ON E.ID_CARRERA = CA.ID_CARRERA
JOIN CAMPUS CP ON CA.ID_CAMPUS = CP.ID_CAMPUS 
JOIN CIUDAD CI ON CP.ID_CIUDAD = CI.ID_CIUDAD;

--9 TITULO DEL LIBRO, EDITORIAL Y PAIS DE ORIGEN
SELECT L.TITULO, ED.NOMBRE AS EDITORIAL, ED.PAIS 
FROM LIBROS L
JOIN EDITORIALES ED ON L.ID_EDITORIAL = ED.ID_EDITORIAL;  

--10 TITULO DEL LIBRO Y NOMBRE DE LA BIBLIOTECA DONDE SE UBICA
SELECT L.TITULO, B.BIBLIOTECA
FROM LIBROS L
JOIN BIBLIOTECA B ON L.ID_BIBLIOTECA = B.ID_BIBLIOTECA;

-- AGREGACIONES Y AGRUPAMIENTOS CON GROUP BY Y HAVING

--11 CANTIDAD DE LIBROS REGISTRADOS POR CADA TIPO DE PUBLICACION
SELECT T.TIPO_P, COUNT(L.COD_LIBRO) AS CANTIDAD_LIBROS
FROM TIPO T  
LEFT JOIN LIBROS L ON T.ID_TIPO = L.ID_TIPO
GROUP BY T.ID_TIPO, T.TIPO_P; 

--12 EDAD PROMEDIO DE LOS ESTUDIANTES
SELECT C.NOMBRE AS CARRERA, AVG(E.EDAD) AS EDAD_PROMEDIO
FROM ESTUDIANTES E
JOIN CARRERAS C ON E.ID_CARRERA = C.ID_CARRERA
GROUP BY C.ID_CARRERA, C.NOMBRE;

--13 FUNCIONARIO Y TOTAL DE PRESTAMOS REALIZADOS
SELECT
    F.NOMBRE,
    F.APELLIDO,
    COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM FUNCIONARIOS F
LEFT JOIN PRESTAMOS P ON F.RUT_FUNC = P.RUT_FUNC
GROUP BY F.RUT_FUNC, F.NOMBRE, F.APELLIDO
ORDER BY TOTAL_PRESTAMOS DESC;

--114 AUTORES CON MAS DE 1 LIBRO REGISTRADO EN EL SISTEMA
SELECT A.RUT_AUTOR, A.NOMBRE, A.APELLIDO, COUNT(L.COD_LIBRO) AS
CANTIDAD_LIBROS
FROM AUTORES A
JOIN LIBROS L ON A.RUT_AUTOR = L.RUT_AUTOR
GROUP BY A.RUT_AUTOR, A.NOMBRE, A.APELLIDO
HAVING COUNT(L.COD_LIBRO) >= 1;

--15 NOMBRE DE LA CIUDAD Y CANTIDAD DE ESTUDAINTE QUE ESTUDIAN EN ELLA
SELECT CI.NOMBRE AS CIUDAD, COUNT(E.RUT_EST) AS CANTIDAD_ESTUDIANTES
FROM ESTUDIANTES E
JOIN CARRERAS CA ON E.ID_CARRERA = CA.ID_CARRERA
JOIN CAMPUS CP ON CA.ID_CAMPUS = CP.ID_CAMPUS
JOIN CIUDAD CI ON CP.ID_CIUDAD = CI.ID_CIUDAD
GROUP BY CI.ID_CIUDAD, CI.NOMBRE;

-- SUBCONSULTAS, EXCLUSIONES Y LIMITES

--16 TITULO Y AÑO DEL LIBRO MAS ANTIGUO DE LA BIBLIOTECA
SELECT TITULO, AGNO
FROM LIBROS
WHERE AGNO = (SELECT MIN(AGNO) FROM LIBROS);

--17 ESTUDIANTES QUE NO PIDIERON PRESTADO
SELECT E.RUT_EST, E.NOMBRE, E.APELLIDO
FROM ESTUDIANTES E
LEFT JOIN PRESTAMOS P ON E.RUT_EST = P.RUT_EST
WHERE P.RUT_EST IS NULL;

--18 LIBROS NUNCA PRESTADOS
SELECT L.COD_LIBRO, L.TITULO
FROM LIBROS L
LEFT JOIN PRESTAMOS P ON L.COD_LIBRO = P.COD_LIBRO
WHERE P.COD_LIBRO IS NULL

--19 PRESTAMOS REALIZADOS DURANTE EL MES ANTERIOR
SELECT *
FROM PRESTAMOS
WHERE MONTH(FECHA_P) = MONTH(CURRENT_DATE - INTERVAL 1 MONTH) AND YEAR(FECHA_P) = YEAR(CURRENT_DATE - INTERVAL 1 MONTH);

--20 LIBROS MAS PRESTADOS DE LA BIBLIOTECA
SELECT L.TITULO, COUNT(P.COD_LIBRO) AS TOTAL_PRESTAMOS
FROM LIBROS L
JOIN PRESTAMOS P ON L.COD_LIBRO = P.COD_LIBRO
GROUP BY L.COD_LIBRO, L.TITULO
ORDER BY TOTAL_PRESTAMOS DESC
LIMIT 3;
