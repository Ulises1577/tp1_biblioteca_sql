--1 Ver detalle de prestamo
CREATE VIEW VW_PRESTAMOS_DETALLE AS
SELECT
    P.FECHA_P AS FECHA_PRESTAMO,
    CONCAT(E.NOMBRE, ' ', E.APELLIDO) AS NOMBRE_ESTUDIANTE,
    L.TITULO AS TITULO_LIBRO,
    CONCAT(F.NOMBRE, ' ', F.APELLIDO) AS NOMBRE_FUNCIONARIO,
    C.NOMBRE AS CARRERA_ESTUDIANTE
FROM PRESTAMOS P
JOIN ESTUDIANTES E ON P.RUT_EST = E.RUT_EST
JOIN LIBROS L ON P.COD_LIBRO = L.COD_LIBRO
JOIN FUNCIONARIOS F ON P.RUT_FUNC = F.RUT_FUNC
JOIN CARRERAS C ON E.ID_CARRERA = C.ID_CARRERA;

SELECT * FROM VW_PRESTAMOS_DETALLE

--2 MUESTRA EL NOMBRE DE LA BIBLIOTECA Y LA CANTIDAD OTAL DEL LIBROS

CREATE VIEW VW_LIBROS_POR_BIBLIOTECA AS 
SELECT
    B.BIBLIOTECA AS NOMBRE_BIBLIOTECA,
    COUNT(L.COD_LIBRO) AS TOTAL_LIBROS
FROM BIBLIOTECA B
LEFT JOIN LIBROS L ON B.ID_BIBLIOTECA = L.ID_BIBLIOTECA
GROUP BY B.ID_BIBLIOTECA, B.BIBLIOTECA;

SELECT * FROM VW_LIBROS_POR_BIBLIOTECA